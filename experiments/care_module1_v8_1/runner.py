#!/usr/bin/env python3
"""Phi-4 + TrialMatchAI V8.1 inference, stage checkpoints and auditable reuse."""
import argparse, copy, hashlib, json, os, sys, time, traceback
from pathlib import Path
HERE=Path(__file__).resolve().parent; REPO=HERE.parents[1]
sys.path.insert(0,str(REPO))
from experiments.care_module1_v8_1.prompts import prediction_input, messages_for, parse_output
BASE='/home/gcx/models/care_module1_v5/phi-4'
ADAPTER='/home/gcx/models/care_module1_v5/trialmatchai-phi4-reasoning-lora'
EXAMPLES=REPO/'experiments/care_module1_semantic_v8/data/fewshot_examples.json'
PREFIX='{"rules":['

def rows(path):
    return [json.loads(s) for s in Path(path).read_text().splitlines() if s.strip()] if path and Path(path).exists() else []
def save(path,obj):
    tmp=path.with_suffix('.tmp');tmp.write_text(json.dumps(obj,ensure_ascii=False,indent=2)+'\n');tmp.replace(path)
def digest(path): return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--cases',type=Path,required=True);ap.add_argument('--arm',choices=['A1','B1','B2'],required=True)
    ap.add_argument('--output',type=Path,required=True);ap.add_argument('--split');ap.add_argument('--batch-size',type=int,default=8)
    ap.add_argument('--max-new-tokens',type=int,default=384)
    ap.add_argument('--first-pass-cache',type=Path);ap.add_argument('--reuse-cache',type=Path)
    args=ap.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    examples=json.loads(EXAMPLES.read_text());source=rows(args.cases)
    if args.split:source=[r for r in source if r.get('split')==args.split]
    output=args.output/'predictions.jsonl';checkpoint=args.output/'stages.jsonl'
    done={r['case_id'] for r in rows(output)}
    requests=[{'case_id':c['case_id'],'input':prediction_input(c),'attempts':[]} for c in source if c['case_id'] not in done]
    cache={r['case_id']:r for r in rows(args.first_pass_cache or args.reuse_cache)}
    stages={(r['case_id'],r['stage']):r for r in rows(checkpoint)}
    start=time.perf_counter()
    manifest={'status':'preparing','arm':args.arm,'base_model':BASE,'adapter_model':ADAPTER,
      'input_path':str(args.cases.resolve()),'input_sha256':digest(args.cases),'total_cases':len(source),
      'generation':{'batch_size':args.batch_size,'max_new_tokens':args.max_new_tokens,'do_sample':False,'num_beams':1,'assistant_prefix':PREFIX},
      'quantization':'NF4 4bit, double quantization, bfloat16 compute via unchanged TrialMatchAIAdapter',
      'first_pass_cache':str(args.first_pass_cache) if args.first_pass_cache else None,
      'reuse_cache':str(args.reuse_cache) if args.reuse_cache else None,
      'cache_sha256':digest(args.first_pass_cache or args.reuse_cache) if args.first_pass_cache or args.reuse_cache else None,
      'prompt_sha256':digest(HERE/'prompts.py'),'original_prompt_sha256':digest(REPO/'experiments/care_module1_semantic_v8/prompts.py'),
      'fewshot_sha256':digest(EXAMPLES),'runner_sha256':digest(__file__),
      'python_executable':sys.executable,'cuda_visible_devices':os.environ.get('CUDA_VISIBLE_DEVICES'),
      'failure_policy':'one JSON-format retry per stage; persistent technical failure null, never U',
      'logical_cost':'all attempts, including reused A1 first pass','added_cost':'attempts generated by V8.1, excluding reused historical/A1 attempts'}
    def log(event,**kw):
        row={'event':event,'elapsed_seconds':time.perf_counter()-start,**kw}
        with (args.output/'events.jsonl').open('a') as f:f.write(json.dumps(row)+'\n')
        print(json.dumps(row),flush=True)
    def reuse(item, cached):
        attempts=copy.deepcopy(cached['attempts'])
        for a in attempts:a.update(stage='initial',reused=True,cache_path=str(args.first_pass_cache or args.reuse_cache))
        # Verify the supplied patient/rules were actually present in the cached prompt.
        expected=messages_for(item['input'],'A1',examples)[-1]['content']
        if expected not in attempts[0]['prompt']:raise ValueError('Cache input mismatch: '+item['case_id'])
        item['attempts']=attempts;item['parsed']=copy.deepcopy(cached['rules'])
    def finish(item,stream):
        parsed=item.get('parsed');status='ok' if parsed is not None and all(r.get('state') in ('T','F','U') for r in parsed) else 'parse_failure'
        if status!='ok':parsed=[{'rule_id':r['rule_id'],'state':None,'evidence_quote':'','reason_short':''} for r in item['input']['rules']]
        for row in parsed:
            quote=row.get('evidence_quote','');offset=item['input']['patient'].find(quote) if quote else -1
            row['evidence_located']=offset>=0;row['optional_evidence_char_span']=[offset,offset+len(quote)] if offset>=0 else None
        attempts=item['attempts'];added=[a for a in attempts if not a.get('reused',False)]
        record={'case_id':item['case_id'],'arm':args.arm,'status':status,'rules':parsed,'attempts':attempts,
          'model_call_count':len(attempts),'added_model_call_count':len(added),
          'inference_seconds':sum(a['generation_seconds'] for a in attempts),'added_inference_seconds':sum(a['generation_seconds'] for a in added),
          'time_definition':'amortized actual GPU batch generation wall time; excludes loading; full cost includes reused first pass',
          'is_model_prediction':True,'mode':'all_rules_per_case'}
        for key in ('input_tokens','output_tokens'):
            record[key]=sum(a[key] for a in attempts);record['added_'+key]=sum(a[key] for a in added)
        stream.write(json.dumps(record,ensure_ascii=False)+'\n');stream.flush()
    if args.reuse_cache:
        if args.arm!='A1':raise ValueError('--reuse-cache is A1 only')
        with output.open('a') as stream:
            for item in requests:reuse(item,cache[item['case_id']]);finish(item,stream)
        manifest.update(status='completed',execution='cache_reuse',elapsed_seconds=time.perf_counter()-start)
        save(args.output/'manifest.json',manifest);return
    if not requests:log('already_completed',cases=len(done));return
    if args.first_pass_cache:
        if args.arm!='B2':raise ValueError('--first-pass-cache is B2 only')
        for item in requests:reuse(item,cache[item['case_id']])
    import torch,transformers,peft,bitsandbytes
    from src.module1.care_v6 import TrialMatchAIAdapter
    torch.cuda.set_device(0);torch.cuda.reset_peak_memory_stats()
    manifest.update(status='loading',gpu_name=torch.cuda.get_device_name(0),versions={k:v.__version__ for k,v in [('torch',torch),('transformers',transformers),('peft',peft),('bitsandbytes',bitsandbytes)]})
    save(args.output/'manifest.json',manifest);log('loading')
    model=TrialMatchAIAdapter.from_pretrained(device='cuda:0',base_model=BASE,adapter_model=ADAPTER)
    tok=model.tokenizer;tok.padding_side='left'
    if tok.pad_token_id is None:tok.pad_token_id=tok.eos_token_id
    manifest.update(status='running',model_load_seconds=time.perf_counter()-start);save(args.output/'manifest.json',manifest);log('loaded')
    def generate(items,stage,retry=False):
        prompts=[];message_lists=[]
        for item in items:
            draft=item['draft'] if stage=='review' else None
            messages=messages_for(item['input'],args.arm if stage=='review' or args.arm!='B2' else 'A1',examples,draft)
            if retry:
                messages += [{'role':'assistant','content':item['attempts'][-1]['raw_output']},
                 {'role':'user','content':'The answer did not match the JSON output format. Return the complete JSON object with exactly the supplied rule IDs, T/F/U states, short evidence_quote and reason_short strings. Keep quotes and reasons short. No extra text.'}]
            message_lists.append(messages);prompts.append(tok.apply_chat_template(messages,tokenize=False,add_generation_prompt=True)+PREFIX)
        enc=tok(prompts,padding=True,return_tensors='pt').to('cuda:0');torch.cuda.synchronize();t0=time.perf_counter()
        with torch.inference_mode():
            out=model.model.generate(**enc,max_new_tokens=args.max_new_tokens,do_sample=False,num_beams=1,pad_token_id=tok.pad_token_id,eos_token_id=tok.eos_token_id)
        torch.cuda.synchronize();elapsed=time.perf_counter()-t0
        for item,prompt,messages,tokens,mask in zip(items,prompts,message_lists,out[:,enc['input_ids'].shape[1]:],enc['attention_mask']):
            ids=tokens.tolist();n=ids.index(tok.eos_token_id)+1 if tok.eos_token_id in ids else len(ids)
            raw=PREFIX+tok.decode(ids[:n],skip_special_tokens=True);parsed,error=parse_output(raw,[r['rule_id'] for r in item['input']['rules']])
            item['attempts'].append({'stage':stage,'reused':False,'attempt':2 if retry else 1,'prompt':prompt,'messages':messages,'raw_output':raw,
              'parse_status':'accepted' if parsed is not None else 'failed','error':error,
              'generation_seconds':elapsed/len(items),'batch_generation_seconds':elapsed,'batch_size':len(items),
              'input_tokens':int(mask.sum()),'output_tokens':n,'truncated':n==args.max_new_tokens and ids[n-1]!=tok.eos_token_id})
            item['parsed']=parsed
        log('batch_generated',stage=stage,retry=retry,cases=len(items),seconds=elapsed)
    def run_stage(batch,stage):
        pending=[]
        for item in batch:
            saved=stages.get((item['case_id'],stage))
            if saved:item['attempts']=saved['attempts'];item['parsed']=saved['parsed']
            else:pending.append(item)
        if not pending:return
        generate(pending,stage)
        failed=[r for r in pending if r['parsed'] is None]
        if failed:generate(failed,stage,True)
        with checkpoint.open('a') as f:
            for item in pending:f.write(json.dumps({'case_id':item['case_id'],'stage':stage,'attempts':item['attempts'],'parsed':item['parsed']},ensure_ascii=False)+'\n')
    try:
        with output.open('a') as stream:
            for i in range(0,len(requests),args.batch_size):
                batch=requests[i:i+args.batch_size]
                if not args.first_pass_cache:run_stage(batch,'initial')
                if args.arm=='B2':
                    for item in batch:item['draft']=item['attempts'][-1]['raw_output']
                    run_stage(batch,'review')
                for item in batch:finish(item,stream)
                log('batch_completed',completed=i+len(batch),total=len(requests))
        manifest.update(status='completed')
    except Exception as exc:
        manifest.update(status='failed',error=repr(exc));raise
    finally:
        manifest.update(elapsed_seconds=time.perf_counter()-start,peak_allocated_gib=torch.cuda.max_memory_allocated()/1024**3,peak_reserved_gib=torch.cuda.max_memory_reserved()/1024**3)
        save(args.output/'manifest.json',manifest)
if __name__=='__main__':main()
